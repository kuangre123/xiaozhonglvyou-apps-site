/**
 * @param available Map<modelId, manifest 条目>：只有成功加载的造物才进入时间线
 */
export function buildTimeline(available) {
  const shots = [...EARLY];
  let k = 0;
  for (const c of CREATIONS) {
    if (!available.has(c.model)) continue;
    shots.push(creationShot(c, k++, available.get(c.model)));
  }
  shots.push(FINALE);

  let t = 0;
  for (const s of shots) {
    s.start = t;
    s.trans = Math.min(s.trans, s.dur * 0.8);
    s.camTrans = Math.min(s.dur * 0.95, s.trans * 1.35 + 0.6);
    t += s.dur;
  }
  const duration = t;

  /** 影片时间 → 当前镜头索引 */
  const indexAt = (T) => {
    let lo = 0;
    let hi = shots.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (shots[mid].start <= T) lo = mid;
      else hi = mid - 1;
    }
    return lo;
  };

  return { shots, duration, indexAt };
}
